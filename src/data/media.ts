export function photoUrl(id: string, frame: 0 | 1): string {
  return `/ex/${id}-${frame}.jpg`;
}

/** Saca el id de un enlace de YouTube (watch, youtu.be, shorts o embed) */
export function youtubeId(url: string): string | null {
  const m = /(?:youtu\.be\/|youtube\.com\/(?:watch\?(?:.*&)?v=|shorts\/|embed\/|live\/))([\w-]{11})/.exec(url.trim());
  return m ? m[1] : null;
}

export function youtubeSearchUrl(name: string): string {
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(`${name} técnica correcta`)}`;
}
